-- USER Table
CREATE TABLE IF NOT EXISTS USER (
    user_id INT PRIMARY KEY AUTO_INCREMENT,
    user_name VARCHAR(30) NOT NULL,
    fname VARCHAR(30) NOT NULL,
    lname VARCHAR(30) NOT NULL,
    bio TEXT DEFAULT NULL,
    avatar_url VARCHAR(225) DEFAULT 'url/',
    email VARCHAR(225) DEFAULT NULL,
    password VARCHAR(225) NOT NULL,
    is_banned BOOLEAN NOT NULL DEFAULT FALSE,
    is_annonymous BOOLEAN NOT NULL DEFAULT FALSE,
    create_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- VOICE_MEMO Table
CREATE TABLE IF NOT EXISTS VOICE_MEMO (
    memo_id INT PRIMARY KEY AUTO_INCREMENT,
    pin_id INT NOT NULL,
    latitude DECIMAL(10, 8) NOT NULL,
    longitude DECIMAL(11, 8) NOT NULL,
    location_name VARCHAR(128) NOT NULL,
    audio_file_url VARCHAR(128) NOT NULL,
    duration_seconds INT NOT NULL,
    is_anonymous BOOLEAN NOT NULL DEFAULT FALSE,
    status ENUM('ACTIVE', 'EXPIRED', 'DELETED', 'FLAGGED') NOT NULL DEFAULT 'ACTIVE',
    expires_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (pin_id) REFERENCES USER(user_id) ON DELETE CASCADE
);

-- REPLY_MEMO Table
CREATE TABLE IF NOT EXISTS REPLY_MEMO (
    reply_id INT PRIMARY KEY AUTO_INCREMENT,
    memo_id INT NOT NULL,
    user_id INT NOT NULL,
    audio_file_url VARCHAR(128) NOT NULL,
    duration_seconds INT NOT NULL,
    create_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (memo_id) REFERENCES VOICE_MEMO(memo_id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES USER(user_id) ON DELETE CASCADE
);

-- REPORT Table
CREATE TABLE IF NOT EXISTS REPORT (
    report_id INT PRIMARY KEY AUTO_INCREMENT,
    memo_id INT NOT NULL,
    reporter_user_id INT NOT NULL,
    reason TEXT DEFAULT NULL,
    create_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (memo_id) REFERENCES VOICE_MEMO(memo_id) ON DELETE CASCADE,
    FOREIGN KEY (reporter_user_id) REFERENCES USER(user_id) ON DELETE CASCADE
);
